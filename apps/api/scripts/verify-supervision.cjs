/* Permission regression against a real database. All fixtures and changes roll back. */
const assert = require('node:assert/strict');
const { PrismaClient } = require('@prisma/client');
const { SupervisionService } = require('../dist/modules/teacher/supervision.service');
const { TeacherService } = require('../dist/modules/teacher/teacher.service');
const { AdminService } = require('../dist/modules/admin/admin.service');
const { validate } = require('class-validator');
const { plainToInstance } = require('class-transformer');
const { SupervisionQueryDto } = require('../dist/modules/teacher/dto/supervision-query.dto');
const { UpdateTeacherDto } = require('../dist/modules/admin/dto/update-teacher.dto');
const prisma = new PrismaClient();
const rollback = new Error('SUPERVISION_VERIFICATION_ROLLBACK');
const rejectsStatus = (task, status) => assert.rejects(task, e => e.getStatus?.() === status);
async function main() {
  assert.equal(process.env.VERIFY_SUPERVISION_ROLLBACK, '1', 'Set VERIFY_SUPERVISION_ROLLBACK=1 to run the rolled-back verification');
  assert((await validate(plainToInstance(SupervisionQueryDto, {page:'0',pageSize:'101'}))).length);
  assert((await validate(plainToInstance(SupervisionQueryDto, {from:'invalid'}))).length);
  assert((await validate(plainToInstance(UpdateTeacherDto, {managedCampusIds:['A','A']}))).length);
  try {
    await prisma.$transaction(async tx => {
      const db = new Proxy(tx, { get(target,key) { return key === '$transaction' ? ops => Promise.all(ops) : target[key]; } });
      const audit = {log: async () => {}};
      const service = new SupervisionService(db);
      const teacherService = new TeacherService(db, audit, {});
      const admin = new AdminService(db, audit, {}, {handleTeacherAccountChange:async()=>{}});
      const a = await tx.campus.create({data:{name:'verification-campus-A'}});
      const b = await tx.campus.create({data:{name:'verification-campus-B'}});
      const user = async (name,extra={})=>tx.user.create({data:{name,role:'teacher',teacherPositions:['teacher'],...extra}});
      const lead = await user('verification-supervisor',{teacherPositions:['supervisor','teacher'],managedCampuses:{connect:{id:a.id}}});
      const empty = await user('verification-unassigned',{teacherPositions:['supervisor']});
      const author = await user('verification-former-teacher',{employmentStatus:'resigned',status:'disabled'});
      const ordinary = await user('verification-ordinary');
      const ca = await tx.class.create({data:{name:'verification-class-A',campusId:a.id,teacherId:author.id}});
      const cb = await tx.class.create({data:{name:'verification-class-B',campusId:b.id,teacherId:ordinary.id}});
      const plan = async (classId,teacherId,status,publishedAt=null)=>tx.lessonPlan.create({data:{classId,teacherId,status,publishedAt,theme:'verification-plan',lessonDate:new Date('2026-10-26T23:30:00Z'),durationMinutes:45,objectives:'目标',content:'内容'}});
      const published = await plan(ca.id,author.id,'published',new Date());
      const archived = await plan(ca.id,author.id,'archived',new Date());
      const draft = await plan(ca.id,author.id,'draft',new Date());
      const unproven = await plan(ca.id,author.id,'archived');
      const outside = await plan(cb.id,ordinary.id,'published',new Date());
      const record = await tx.teachingRecord.create({data:{classId:ca.id,teacherId:author.id,date:new Date('2026-10-26T23:30:00Z'),course:'课后记录',content:'内容',tags:[`lesson-plan:${published.id}`]}});
      await tx.teachingRecord.create({data:{classId:cb.id,teacherId:ordinary.id,date:new Date(),course:'外校区',content:'内容'}});
      const context = (await service.context(lead.id)).data;
      assert.deepEqual(context.campuses.map(c=>c.id),[a.id]);
      assert(context.teachers.some(t=>t.id===author.id));
      assert(!context.teachers.some(t=>t.id===ordinary.id));
      assert.deepEqual(Object.keys(context.teachers[0]).sort(),['id','name']);
      await rejectsStatus(()=>service.lessonPlans(ordinary.id,{}),403);
      assert.equal((await service.lessonPlans(empty.id,{})).data.total,0);
      const list = (await service.lessonPlans(lead.id,{})).data;
      assert.equal(list.total,2);
      assert.deepEqual(list.items.map(p=>p.id).sort(),[published.id,archived.id].sort());
      assert.equal(list.items.find(p=>p.id===published.id).teachingCompleted,true);
      assert.equal(list.items.find(p=>p.id===archived.id).teachingCompleted,false);
      assert.equal((await service.lessonPlans(lead.id,{teacherId:ordinary.id})).data.total,0);
      assert.equal((await service.lessonPlans(lead.id,{classId:cb.id})).data.total,0);
      assert.equal((await service.lessonPlans(lead.id,{from:'2026-10-27',to:'2026-10-27'})).data.total,2);
      assert.equal((await service.lessonPlans(lead.id,{from:'2026-10-26',to:'2026-10-26'})).data.total,0);
      await rejectsStatus(()=>service.lessonPlans(lead.id,{from:'2026-10-28',to:'2026-10-27'}),400);
      await rejectsStatus(()=>service.lessonPlans(lead.id,{campusId:b.id}),403);
      for (const p of [draft,unproven,outside]) await rejectsStatus(()=>service.detail(lead.id,'lesson',p.id),404);
      assert.equal((await service.teachingRecords(lead.id,{})).data.total,1);
      assert.equal((await service.detail(lead.id,'record',record.id)).data.content,'内容');
      await rejectsStatus(()=>teacherService.updateLessonPlanStatus(lead.id,published.id,{status:'draft'}),404);
      await rejectsStatus(()=>teacherService.createTeachingRecord(lead.id,{classId:ca.id,date:'2026-10-27',course:'x',content:'x'}),403);
      // Exercise all four publication write paths with actual database rows.
      await tx.class.update({where:{id:ca.id},data:{teacherId:ordinary.id}});
      const dto={classId:ca.id,theme:'主题',lessonDate:'2026-10-27',durationMinutes:45,objectives:'目标',content:'内容'};
      const created = (await teacherService.createLessonPlan(ordinary.id,{...dto,status:'published'})).data;
      assert(created.publishedAt);
      const editable = (await teacherService.createLessonPlan(ordinary.id,{...dto,status:'draft'})).data;
      assert.equal(editable.publishedAt,null);
      assert((await teacherService.updateLessonPlan(ordinary.id,editable.id,{status:'published'})).data.publishedAt);
      const statusPlan = (await teacherService.createLessonPlan(ordinary.id,{...dto,status:'draft'})).data;
      const first = (await teacherService.updateLessonPlanStatus(ordinary.id,statusPlan.id,{status:'published'})).data.publishedAt;
      assert(first);
      assert.equal((await teacherService.updateLessonPlanStatus(ordinary.id,statusPlan.id,{status:'archived'})).data.publishedAt.getTime(),first.getTime());
      await teacherService.updateLessonPlanStatus(ordinary.id,statusPlan.id,{status:'draft'});
      await rejectsStatus(()=>service.detail(lead.id,'lesson',statusPlan.id),404);
      const adminPlan = (await teacherService.createLessonPlan(ordinary.id,{...dto,status:'draft'})).data;
      assert((await admin.updateLessonPlanStatus(lead.id,adminPlan.id,'published')).data.publishedAt);
      // Configuration validation and revocation must take effect without re-login.
      await rejectsStatus(()=>admin.updateTeacher(lead.id,ordinary.id,{managedCampusIds:[a.id]}),400);
      await rejectsStatus(()=>admin.updateTeacher(lead.id,lead.id,{managedCampusIds:['missing-campus']}),400);
      await admin.updateTeacher(lead.id,lead.id,{managedCampusIds:[a.id,b.id]});
      assert.equal((await service.context(lead.id)).data.campuses.length,2);
      assert.equal((await service.detail(lead.id,'lesson',outside.id)).data.id,outside.id);
      await admin.updateTeacher(lead.id,lead.id,{managedCampusIds:[]});
      assert.equal((await service.lessonPlans(lead.id,{})).data.total,0);
      await rejectsStatus(()=>service.detail(lead.id,'lesson',published.id),404);
      await admin.updateTeacher(lead.id,lead.id,{managedCampusIds:[a.id]});
      await admin.updateTeacher(lead.id,lead.id,{teacherPositions:['teacher']});
      assert.equal((await tx.user.findUnique({where:{id:lead.id},include:{managedCampuses:true}})).managedCampuses.length,0);
      assert.equal((await service.context(lead.id)).data.isSupervisor,false);
      await rejectsStatus(()=>service.teachingRecords(lead.id,{}),403);
      await tx.user.update({where:{id:lead.id},data:{teacherPositions:['supervisor'],employmentStatus:'resigned'}});
      await rejectsStatus(()=>service.teachingRecords(lead.id,{}),403);
      throw rollback;
    },{timeout:60000});
  } catch (e) { if(e!==rollback) throw e; }
  console.log('PASS: 校区隔离、只读所有权、草稿与归档保护、离职教师历史、日期边界、四条发布路径、多校区配置及即时撤权；全部测试数据已回滚。');
}
main().catch(e=>{console.error(e);process.exitCode=1}).finally(()=>prisma.$disconnect());
